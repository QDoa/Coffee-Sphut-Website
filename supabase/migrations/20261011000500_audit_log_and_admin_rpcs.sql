-- Generic trigger function to record staff mutations on content, cafe, waitlist, and team tables
CREATE OR REPLACE FUNCTION public.audit_log_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor_id uuid;
  v_actor_role text;
  v_actor_email text;
  v_old jsonb;
  v_new jsonb;
  v_row jsonb;
  v_record_id text;
  v_action text;
  v_changed_fields text[];
  v_reason text;
BEGIN
  -- Only log changes made by authenticated staff members (editors or admins)
  IF NOT public.is_staff() THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  v_actor_id := auth.uid();
  v_actor_role := public.staff_role();
  SELECT u.email INTO v_actor_email FROM auth.users u WHERE u.id = v_actor_id;

  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    v_old := to_jsonb(OLD) - ARRAY['fts_vectors', 'location'];
  END IF;

  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    v_new := to_jsonb(NEW) - ARRAY['fts_vectors', 'location'];
  END IF;

  v_row := COALESCE(v_new, v_old);
  v_record_id := COALESCE(
    v_row->>'id',
    v_row->>'cafe_id',
    v_row->>'user_id',
    CASE
      WHEN v_row ? 'post_id' AND v_row ? 'category_id'
      THEN (v_row->>'post_id') || ':' || (v_row->>'category_id')
      ELSE 'unknown'
    END
  );

  v_action := lower(TG_OP);

  IF TG_OP = 'UPDATE' THEN
    SELECT coalesce(array_agg(k ORDER BY k), '{}'::text[])
    INTO v_changed_fields
    FROM (
      SELECT k
      FROM jsonb_object_keys(v_old || v_new) AS k
      WHERE k <> 'updated_at'
        AND (v_old->k) IS DISTINCT FROM (v_new->k)
    ) diff;

    -- Skip logging no-op updates
    IF cardinality(v_changed_fields) = 0 THEN
      RETURN NEW;
    END IF;

    -- Semantic action names for publishing state transitions on Post, Recipe, and Event
    IF TG_TABLE_NAME IN ('Post', 'Recipe', 'Event')
       AND (v_old->>'published_at') IS DISTINCT FROM (v_new->>'published_at') THEN
      IF v_new->>'published_at' IS NULL THEN
        v_action := lower(TG_TABLE_NAME) || '.unpublish';
      ELSIF (v_new->>'published_at')::timestamptz > now() THEN
        v_action := lower(TG_TABLE_NAME) || '.schedule';
      ELSIF v_old->>'published_at' IS NULL OR (v_old->>'published_at')::timestamptz > now() THEN
        v_action := lower(TG_TABLE_NAME) || '.publish';
      END IF;
    ELSIF TG_TABLE_NAME = 'AdminUser' AND (v_old->>'role') IS DISTINCT FROM (v_new->>'role') THEN
      v_action := 'team.role_change';
    END IF;
  ELSIF TG_OP = 'INSERT' AND TG_TABLE_NAME = 'AdminUser' THEN
    v_action := 'team.add';
  ELSIF TG_OP = 'DELETE' AND TG_TABLE_NAME = 'AdminUser' THEN
    v_action := 'team.remove';
  END IF;

  v_reason := nullif(btrim( coalesce(current_setting('app.audit_reason', true), '') ), '');

  INSERT INTO public."AdminAuditLog" (
    actor_id,
    actor_email,
    actor_role,
    action,
    table_name,
    record_id,
    old_data,
    new_data,
    changed_fields,
    reason
  ) VALUES (
    v_actor_id,
    v_actor_email,
    v_actor_role,
    v_action,
    TG_TABLE_NAME,
    v_record_id,
    v_old,
    v_new,
    v_changed_fields,
    v_reason
  );

  RETURN COALESCE(NEW, OLD);
END;
$$;

ALTER FUNCTION public.audit_log_change() OWNER TO postgres;

