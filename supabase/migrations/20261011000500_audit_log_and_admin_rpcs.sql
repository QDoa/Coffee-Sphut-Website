CREATE TABLE IF NOT EXISTS public."AdminAuditLog" (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_email text,
  actor_role text,
  action text NOT NULL,
  table_name text NOT NULL,
  record_id text NOT NULL,
  old_data jsonb,
  new_data jsonb,
  changed_fields text[],
  reason text,
  CONSTRAINT "AdminAuditLog_pkey" PRIMARY KEY (id)
);

ALTER TABLE public."AdminAuditLog" OWNER TO postgres;

COMMENT ON TABLE public."AdminAuditLog" IS 'Append-only audit trail of all staff changes and admin actions';

CREATE INDEX IF NOT EXISTS admin_audit_log_table_record_idx
  ON public."AdminAuditLog" (table_name, record_id, created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_log_actor_idx
  ON public."AdminAuditLog" (actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_log_created_at_idx
  ON public."AdminAuditLog" (created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_log_action_idx
  ON public."AdminAuditLog" (action, created_at DESC);

ALTER TABLE public."AdminAuditLog" ENABLE ROW LEVEL SECURITY;

-- Only admins can read the audit log; nobody can insert/update/delete directly via client roles
CREATE POLICY "Admins can view AdminAuditLog"
  ON public."AdminAuditLog"
  FOR SELECT
  TO authenticated
  USING (public.is_admin());

