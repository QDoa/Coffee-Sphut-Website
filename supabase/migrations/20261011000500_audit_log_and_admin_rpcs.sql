-- 2. Update handle_reward_redeemed() to also decrement reward_count when a reward is voided,
--    clamp at 0, fix NULLs, and lock search_path.
CREATE OR REPLACE FUNCTION public.handle_reward_redeemed()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF OLD.status = 'issued' AND NEW.status IN ('redeemed', 'voided') THEN
    UPDATE public."UserChainLoyalty"
    SET reward_count = GREATEST(COALESCE(reward_count, 0) - 1, 0),
        updated_at = now()
    WHERE user_id = NEW.user_id
      AND chain_id = NEW.chain_id;
  END IF;

  RETURN NEW;
END;
$$;

ALTER FUNCTION public.handle_reward_redeemed() OWNER TO postgres;

-- 3. RPC: admin_reset_onboarding
CREATE OR REPLACE FUNCTION public.admin_reset_onboarding(
  p_user_id uuid,
  p_reason text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor_id uuid;
  v_actor_email text;
  v_old public."Profile"%rowtype;
  v_new public."Profile"%rowtype;
  v_clean_reason text;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Access denied: admin role required' USING ERRCODE = '42501';
  END IF;

  v_clean_reason := nullif(btrim(coalesce(p_reason, '')), '');
  IF v_clean_reason IS NULL THEN
    RAISE EXCEPTION 'A reason is required to reset onboarding' USING ERRCODE = '22023';
  END IF;

  SELECT *
  INTO v_old
  FROM public."Profile"
  WHERE id = p_user_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Profile not found for user %', p_user_id USING ERRCODE = 'P0002';
  END IF;

  UPDATE public."Profile"
  SET onboarding_completed = false,
      onboarding_responses = NULL
  WHERE id = p_user_id
  RETURNING * INTO v_new;

  v_actor_id := auth.uid();
  SELECT u.email INTO v_actor_email FROM auth.users u WHERE u.id = v_actor_id;

  INSERT INTO public."AdminAuditLog" (
    actor_id,
    actor_email,
    actor_role,
    action,
    table_name,
    record_id,
    old_data,
    new_data,
    changed_fields,
    reason
  ) VALUES (
    v_actor_id,
    v_actor_email,
    'admin',
    'onboarding.reset',
    'Profile',
    p_user_id::text,
    to_jsonb(v_old),
    to_jsonb(v_new),
    ARRAY['onboarding_completed', 'onboarding_responses'],
    v_clean_reason
  );
END;
$$;

ALTER FUNCTION public.admin_reset_onboarding(uuid, text) OWNER TO postgres;

-- 4. RPC: admin_adjust_punch_count
CREATE OR REPLACE FUNCTION public.admin_adjust_punch_count(
  p_user_id uuid,
  p_chain_id uuid,
  p_new_count bigint,
  p_reason text
)
RETURNS public."UserChainLoyalty"
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor_id uuid;
  v_actor_email text;
  v_threshold integer;
  v_old public."UserChainLoyalty"%rowtype;
  v_new public."UserChainLoyalty"%rowtype;
  v_had_existing boolean := true;
  v_clean_reason text;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Access denied: admin role required' USING ERRCODE = '42501';
  END IF;

  v_clean_reason := nullif(btrim(coalesce(p_reason, '')), '');
  IF v_clean_reason IS NULL THEN
    RAISE EXCEPTION 'A reason is required to adjust punch count' USING ERRCODE = '22023';
  END IF;

  SELECT c.loyalty_threshold
  INTO v_threshold
  FROM public."Chains" c
  WHERE c.id = p_chain_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Chain % not found', p_chain_id USING ERRCODE = 'P0002';
  END IF;

  IF p_new_count IS NULL OR p_new_count < 0 OR p_new_count >= v_threshold THEN
    RAISE EXCEPTION 'Punch count must be between 0 and % (below chain threshold of %)',
      v_threshold - 1, v_threshold
      USING ERRCODE = '22023';
  END IF;

  SELECT *
  INTO v_old
  FROM public."UserChainLoyalty"
  WHERE user_id = p_user_id
    AND chain_id = p_chain_id
  FOR UPDATE;

  IF NOT FOUND THEN
    v_had_existing := false;
    INSERT INTO public."UserChainLoyalty" (
      user_id,
      chain_id,
      punch_count,
      reward_count,
      updated_at
    ) VALUES (
      p_user_id,
      p_chain_id,
      p_new_count,
      0,
      now()
    )
    RETURNING * INTO v_new;
  ELSE
    UPDATE public."UserChainLoyalty"
    SET punch_count = p_new_count,
        reward_count = COALESCE(reward_count, 0),
        updated_at = now()
    WHERE id = v_old.id
    RETURNING * INTO v_new;
  END IF;

  v_actor_id := auth.uid();
  SELECT u.email INTO v_actor_email FROM auth.users u WHERE u.id = v_actor_id;

  INSERT INTO public."AdminAuditLog" (
    actor_id,
    actor_email,
    actor_role,
    action,
    table_name,
    record_id,
    old_data,
    new_data,
    changed_fields,
    reason
  ) VALUES (
    v_actor_id,
    v_actor_email,
    'admin',
    'loyalty.adjust_punches',
    'UserChainLoyalty',
    v_new.id::text,
    CASE WHEN v_had_existing THEN to_jsonb(v_old) ELSE NULL END,
    to_jsonb(v_new),
    ARRAY['punch_count'],
    v_clean_reason
  );

  RETURN v_new;
END;
$$;

ALTER FUNCTION public.admin_adjust_punch_count(uuid, uuid, bigint, text) OWNER TO postgres;

-- 5. RPC: admin_void_reward
CREATE OR REPLACE FUNCTION public.admin_void_reward(
  p_reward_id uuid,
  p_reason text
)
RETURNS public."Rewards"
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor_id uuid;
  v_actor_email text;
  v_old public."Rewards"%rowtype;
  v_new public."Rewards"%rowtype;
  v_clean_reason text;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Access denied: admin role required' USING ERRCODE = '42501';
  END IF;

  v_clean_reason := nullif(btrim(coalesce(p_reason, '')), '');
  IF v_clean_reason IS NULL THEN
    RAISE EXCEPTION 'A reason is required to void a reward' USING ERRCODE = '22023';
  END IF;

  SELECT *
  INTO v_old
  FROM public."Rewards"
  WHERE id = p_reward_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Reward % not found', p_reward_id USING ERRCODE = 'P0002';
  END IF;

  IF v_old.status <> 'issued' THEN
    RAISE EXCEPTION 'Only issued rewards can be voided (current status: %)', v_old.status
      USING ERRCODE = '22023';
  END IF;

  -- Updating status from 'issued' to 'voided' also fires on_reward_redemeed trigger,
  -- which decrements UserChainLoyalty.reward_count by 1 (clamped at 0).
  UPDATE public."Rewards"
  SET status = 'voided',
      voided_at = now()
  WHERE id = p_reward_id
  RETURNING * INTO v_new;

  v_actor_id := auth.uid();
  SELECT u.email INTO v_actor_email FROM auth.users u WHERE u.id = v_actor_id;

  INSERT INTO public."AdminAuditLog" (
    actor_id,
    actor_email,
    actor_role,
    action,
    table_name,
    record_id,
    old_data,
    new_data,
    changed_fields,
    reason
  ) VALUES (
    v_actor_id,
    v_actor_email,
    'admin',
    'reward.void',
    'Rewards',
    p_reward_id::text,
    to_jsonb(v_old),
    to_jsonb(v_new),
    ARRAY['status', 'voided_at'],
    v_clean_reason
  );

  RETURN v_new;
END;
$$;

